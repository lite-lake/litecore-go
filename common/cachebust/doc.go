// Package cachebust 提供内置前端静态资源的缓存自动更新机制。
//
// 一期方案 A（302 版本化兜底）：未版本化的 /static/* 请求返回 302 重定向到
// 带构建版本号的版本化路径，版本化资源在生产环境使用 immutable 长缓存，
// 保证每次构建后浏览器必然拉取最新资源（含高频变动的 locales JSON）。
//
// 版本号来源优先级：
//  1. LITE_BUILD_ID（CI 注入的构建标识，如 20260725_163000_abc1234）
//  2. ./static 目录最大文件 mtime（本地开发 fallback，重启后感知文件变更）
//  3. 进程启动 unix 时间戳（兜底，保证版本号永不为空）
//
// 版本号在进程生命周期内固定一次，多次调用 Version() 返回一致。
//
// 本包不依赖 Gin，仅使用标准库，便于复用与单元测试。
